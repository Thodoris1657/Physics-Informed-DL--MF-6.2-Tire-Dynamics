"""
MF6.2 ``.tir`` (TNO/TYDEX property file) export, import and a reference
evaluator.

Conventions
-----------
``.tir`` files use the ISO-W (TYDEX W-axis) system, in which a positive slip
angle produces a *negative* lateral force (so ``PKY1 < 0`` in every standard
file). The internal model uses ``alpha_int = alpha_ISO`` and
``Fy_int = -Fy_ISO`` (see :mod:`mf62pinn.vehicle`), hence

    PKY1 = -pKy1,   PVY1..4 = -pVy1..4,   all other lateral coefficients unchanged.

The reference evaluator below implements the published MF6.2 pure-lateral
equations in ISO-W directly from a parsed ``.tir`` file, *independently* of
the PyTorch model; the test-suite checks the two agree to machine precision,
which guarantees that the exported file reproduces the identified tyre in
any MF6.2-compliant tool (Adams, CarMaker, VI-CarRealTime, MFeval, ...).

Only the pure-lateral force (Fy0) is identified by this project. All other
coefficient groups are written as neutral placeholders and flagged in the
file header.
"""

from __future__ import annotations

import datetime as _dt
import math
from pathlib import Path
from typing import Dict, Optional, Union

import numpy as np

SIGN_FLIP = {"pKy1", "pVy1", "pVy2", "pVy3", "pVy4"}

_LAT_KEYS = ["PCY1", "PDY1", "PDY2", "PDY3", "PEY1", "PEY2", "PEY3", "PEY4", "PEY5",
             "PKY1", "PKY2", "PKY3", "PKY4", "PKY5", "PKY6", "PKY7",
             "PHY1", "PHY2", "PVY1", "PVY2", "PVY3", "PVY4", "PPY1", "PPY2", "PPY3", "PPY4", "PPY5",
             "RBY1", "RBY2", "RBY3", "RBY4", "RCY1", "REY1", "REY2", "RHY1", "RHY2",
             "RVY1", "RVY2", "RVY3", "RVY4", "RVY5", "RVY6"]

_SCALING_KEYS = ["LFZO", "LCX", "LMUX", "LEX", "LKX", "LHX", "LVX", "LCY", "LMUY", "LEY", "LKY", "LKYC",
                 "LKZC", "LHY", "LVY", "LTR", "LRES", "LXAL", "LYKA", "LVYKA", "LS", "LMX", "LVMX",
                 "LMY", "LMP"]


def internal_to_tir(values: Dict[str, float]) -> Dict[str, float]:
    """Map internal coefficients to ISO-W ``.tir`` lateral coefficients."""
    out = {k: 0.0 for k in _LAT_KEYS}
    out["PKY4"] = 2.0
    for k, v in values.items():
        if not k.startswith("p"):
            continue
        key = k.upper()
        if key in out:
            out[key] = -float(v) if k in SIGN_FLIP else float(v)
    return out


def write_tir(path: Union[str, Path], values: Dict[str, float], Fz0: float, *,
              lmuy: float = 1.0, lky: float = 1.0, tyre_name: str = "FSAE tyre",
              unloaded_radius: float = 0.2054, width: float = 0.1905, rim_radius: float = 0.127,
              rim_width: float = 0.1778, pressure_pa: float = 68947.6, longvl: float = 11.176,
              fz_range=(100.0, 1500.0), alpha_range_deg=(-12.5, 12.5), camber_range_deg=(0.0, 0.0),
              comment: str = "", stds: Optional[Dict[str, float]] = None) -> Path:
    """Write a complete MF6.2 property file (lateral coefficients identified)."""
    lat = internal_to_tir(values)
    scaling = {k: 1.0 for k in _SCALING_KEYS}
    scaling["LMUY"] = float(lmuy)
    scaling["LKY"] = float(lky)
    stamp = _dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    hdr = [
        "!:FILE_TYPE:          tir",
        "!:FILE_VERSION:       3.0",
        "!:TIRE_VERSION:       MF 6.2",
        f"!:COMMENT:            {tyre_name}",
        f"!:COMMENT:            generated by mf62pinn on {stamp}",
        "!:COMMENT:            ONLY PURE-LATERAL (Fy0) COEFFICIENTS ARE IDENTIFIED.",
        "!:COMMENT:            Longitudinal, aligning, overturning and rolling groups are neutral placeholders.",
        "!:COMMENT:            Camber/pressure terms are zero (data at 0 deg IA and one pressure).",
    ]
    for line in comment.splitlines():
        hdr.append(f"!:COMMENT:            {line}")
    L = hdr + [
        "$" + "-" * 70 + "units",
        "[UNITS]",
        "LENGTH                   = 'meter'",
        "FORCE                    = 'newton'",
        "ANGLE                    = 'radians'",
        "MASS                     = 'kg'",
        "TIME                     = 'second'",
        "$" + "-" * 70 + "model",
        "[MODEL]",
        "FITTYP                   = 62                $Magic Formula 6.2",
        "TYRESIDE                 = 'LEFT'",
        f"LONGVL                   = {longvl:.4f}         $Nominal speed",
        "VXLOW                    = 1",
        "ROAD_INCREMENT           = 0.01",
        "ROAD_DIRECTION           = 1",
        "PROPERTY_FILE_FORMAT     = 'USER'",
        "USER_SUB_ID              = 815",
        "N_TIRE_STATES            = 5",
        "USE_MODE                 = 124",
        "HMAX_LOCAL               = 2.5E-4",
        "TIME_SWITCH_INTEG        = 0.1",
        "$" + "-" * 70 + "dimensions",
        "[DIMENSION]",
        f"UNLOADED_RADIUS          = {unloaded_radius:.4f}",
        f"WIDTH                    = {width:.4f}",
        f"RIM_RADIUS               = {rim_radius:.4f}",
        f"RIM_WIDTH                = {rim_width:.4f}",
        "ASPECT_RATIO             = 0.3",
        "$" + "-" * 70 + "operating conditions",
        "[OPERATING_CONDITIONS]",
        f"INFLPRES                 = {pressure_pa:.1f}",
        f"NOMPRES                  = {pressure_pa:.1f}",
        "$" + "-" * 70 + "inertia",
        "[INERTIA]",
        "MASS                     = 4.0               $placeholder",
        "IXX                      = 0.1",
        "IYY                      = 0.2",
        "BELT_MASS                = 3.0",
        "BELT_IXX                 = 0.08",
        "BELT_IYY                 = 0.15",
        "GRAVITY                  = -9.81",
        "$" + "-" * 70 + "vertical",
        "[VERTICAL]",
        f"FNOMIN                   = {Fz0:.4f}",
        "VERTICAL_STIFFNESS       = 90000             $placeholder",
        "VERTICAL_DAMPING         = 50",
        "MC_CONTOUR_A             = 0",
        "MC_CONTOUR_B             = 0",
        "BREFF                    = 8.4",
        "DREFF                    = 0.27",
        "FREFF                    = 0.07",
        "Q_RE0                    = 1",
        "Q_V1                     = 0",
        "Q_V2                     = 0",
        "Q_FZ2                    = 0",
        "Q_FCX                    = 0",
        "Q_FCY                    = 0",
        "Q_CAM                    = 0",
        "PFZ1                     = 0",
        "BOTTOM_OFFST             = 0.01",
        "BOTTOM_STIFF             = 2000000",
        "$" + "-" * 70 + "ranges",
        "[INFLATION_PRESSURE_RANGE]",
        f"PRESMIN                  = {0.8 * pressure_pa:.1f}",
        f"PRESMAX                  = {1.2 * pressure_pa:.1f}",
        "[VERTICAL_FORCE_RANGE]",
        f"FZMIN                    = {fz_range[0]:.2f}",
        f"FZMAX                    = {fz_range[1]:.2f}",
        "[LONG_SLIP_RANGE]",
        "KPUMIN                   = -0.25",
        "KPUMAX                   = 0.25",
        "[SLIP_ANGLE_RANGE]",
        f"ALPMIN                   = {math.radians(alpha_range_deg[0]):.6f}",
        f"ALPMAX                   = {math.radians(alpha_range_deg[1]):.6f}",
        "[INCLINATION_ANGLE_RANGE]",
        f"CAMMIN                   = {math.radians(camber_range_deg[0]):.6f}",
        f"CAMMAX                   = {math.radians(camber_range_deg[1]):.6f}",
        "$" + "-" * 70 + "scaling",
        "[SCALING_COEFFICIENTS]",
    ]
    for k in _SCALING_KEYS:
        note = ""
        if k == "LMUY" and abs(lmuy - 1.0) > 1e-12:
            note = "  $track/rig friction ratio (identified)"
        if k == "LKY" and abs(lky - 1.0) > 1e-12:
            note = "  $track/rig cornering-stiffness ratio"
        L.append(f"{k:<25}= {scaling[k]:.6g}{note}")
    L += ["$" + "-" * 70 + "longitudinal", "[LONGITUDINAL_COEFFICIENTS]"]
    for k in ["PCX1", "PDX1", "PDX2", "PDX3", "PEX1", "PEX2", "PEX3", "PEX4", "PKX1", "PKX2", "PKX3",
              "PHX1", "PHX2", "PVX1", "PVX2", "PPX1", "PPX2", "PPX3", "PPX4", "RBX1", "RBX2", "RBX3",
              "RCX1", "REX1", "REX2", "RHX1"]:
        v = {"PCX1": 1.6, "PDX1": 1.0, "PKX1": 20.0, "RBX1": 10.0, "RBX2": 10.0, "RCX1": 1.0}.get(k, 0.0)
        L.append(f"{k:<25}= {v:.6g}{'  $placeholder' if k == 'PCX1' else ''}")
    L += ["$" + "-" * 70 + "overturning", "[OVERTURNING_COEFFICIENTS]"]
    for k in ["QSX1", "QSX2", "QSX3", "QSX4", "QSX5", "QSX6", "QSX7", "QSX8", "QSX9", "QSX10",
              "QSX11", "QSX12", "QSX13", "QSX14", "PPMX1"]:
        L.append(f"{k:<25}= 0")
    L += ["$" + "-" * 70 + "lateral (IDENTIFIED)", "[LATERAL_COEFFICIENTS]"]
    for k in _LAT_KEYS:
        v = lat[k]
        note = ""
        if stds:
            ik = "p" + k[1] + k[2].lower() + k[3:]          # PKY1 -> pKy1
            if ik in stds and stds[ik] > 0:
                note = f"  $+/- {stds[ik]:.3g} (1 sd)"
        L.append(f"{k:<25}= {v:.10g}{note}")
    L += ["$" + "-" * 70 + "rolling", "[ROLLING_COEFFICIENTS]"]
    for k in ["QSY1", "QSY2", "QSY3", "QSY4", "QSY5", "QSY6", "QSY7", "QSY8"]:
        L.append(f"{k:<25}= {0.01 if k == 'QSY1' else 0}")
    L += ["$" + "-" * 70 + "aligning", "[ALIGNING_COEFFICIENTS]"]
    for k in ["QBZ1", "QBZ2", "QBZ3", "QBZ4", "QBZ5", "QBZ9", "QBZ10", "QCZ1", "QDZ1", "QDZ2", "QDZ3",
              "QDZ4", "QDZ6", "QDZ7", "QDZ8", "QDZ9", "QDZ10", "QDZ11", "QEZ1", "QEZ2", "QEZ3", "QEZ4",
              "QEZ5", "QHZ1", "QHZ2", "QHZ3", "QHZ4", "PPZ1", "PPZ2", "SSZ1", "SSZ2", "SSZ3", "SSZ4"]:
        L.append(f"{k:<25}= {1.0 if k in ('QCZ1',) else 0}")
    L += ["$" + "-" * 70 + "turnslip", "[TURNSLIP_COEFFICIENTS]",
          "PDXP1                    = 0.4", "PDXP2                    = 0", "PDXP3                    = 0",
          "PKYP1                    = 1", "PDYP1                    = 0.4", "PDYP2                    = 0",
          "PDYP3                    = 0", "PDYP4                    = 0", "PHYP1                    = 1",
          "PHYP2                    = 0.15", "PHYP3                    = 0", "PHYP4                    = -4",
          "PECP1                    = 0.5", "PECP2                    = 0", "QDTP1                    = 10",
          "QCRP1                    = 0.2", "QCRP2                    = 0.1", "QBRP1                    = 0.1",
          "QDRP1                    = 1"]
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return path


def read_tir(path: Union[str, Path]) -> Dict[str, float]:
    """Parse ``KEY = value`` pairs of a ``.tir`` file (numeric values only)."""
    out: Dict[str, float] = {}
    for line in Path(path).read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.split("$")[0].strip()
        if not line or line.startswith(("!", "[")) or "=" not in line:
            continue
        k, v = (s.strip() for s in line.split("=", 1))
        v = v.strip("'\"")
        try:
            out[k.upper()] = float(v)
        except ValueError:
            continue
    return out


def tir_fy0(t: Dict[str, float], alpha: np.ndarray, Fz: np.ndarray, gamma: Optional[np.ndarray] = None
            ) -> np.ndarray:
    """
    Reference MF6.2 pure lateral force in ISO-W, straight from ``.tir`` values
    (pressure at nominal, no turn slip). ``alpha`` in rad, returns Fy_ISO [N].
    """
    g = lambda k, d=0.0: float(t.get(k, d))  # noqa: E731
    alpha = np.asarray(alpha, float)
    Fz = np.asarray(Fz, float)
    gam = np.zeros_like(alpha) if gamma is None else np.asarray(gamma, float)
    Fz0p = g("FNOMIN") * g("LFZO", 1.0)
    dfz = (Fz - Fz0p) / Fz0p
    LMUY = g("LMUY", 1.0)
    LMUYp = 10.0 * LMUY / (1.0 + 9.0 * LMUY)
    Kya = (g("PKY1") * Fz0p * (1.0 - g("PKY3") * np.abs(gam))
           * np.sin(g("PKY4", 2.0) * np.arctan(Fz / ((g("PKY2") + g("PKY5") * gam ** 2) * Fz0p)))
           * g("LKY", 1.0))
    SVyg = Fz * (g("PVY3") + g("PVY4") * dfz) * gam * g("LKYC", 1.0) * LMUYp
    Kyg0 = Fz * (g("PKY6") + g("PKY7") * dfz) * g("LKYC", 1.0)
    SHy = (g("PHY1") + g("PHY2") * dfz) * g("LHY", 1.0) + (Kyg0 * gam - SVyg) / (Kya + 1e-12)
    ay = alpha + SHy
    Cy = g("PCY1") * g("LCY", 1.0)
    muy = (g("PDY1") + g("PDY2") * dfz) * (1.0 - g("PDY3") * gam ** 2) * LMUY
    Dy = muy * Fz
    Ey = (g("PEY1") + g("PEY2") * dfz) * (1.0 + g("PEY5") * gam ** 2 - (g("PEY3") + g("PEY4") * gam) * np.sign(ay)) * g("LEY", 1.0)
    Ey = np.minimum(Ey, 1.0)
    By = Kya / (Cy * Dy + 1e-12)
    SVy = Fz * (g("PVY1") + g("PVY2") * dfz) * g("LVY", 1.0) * LMUYp + SVyg
    return Dy * np.sin(Cy * np.arctan(By * ay - Ey * (By * ay - np.arctan(By * ay)))) + SVy


